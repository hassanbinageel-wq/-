"""timing.py — الإحسان: العبارات مربوطة بالتسجيل (حدود من silencedetect، ونصّ كل مقطع متحقَّق منه بـ Whisper small) + غلاف الصوت لحركة الفم."""
import json, os, subprocess
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
VO = os.path.join(HERE, 'assets/vo/voice.wav')
OFF, TAIL, FPS = 1.0, 3.8, 30
PHRASES = [
 (1, 'السلامُ عليكم', .24, 1.21), (1, 'تعلَّمنا معًا عن الإسلامِ والإيمان', 1.72, 4.18), (1, 'واليومَ سنتعرَّفُ على الإحسان!', 4.46, 7.17),
 (2, 'هل جرَّبتم أن تنجزوا واجبًا والمعلِّمُ ينظرُ إليكم؟', 7.75, 11.62), (2, 'تحاولون أن تكتبوا بتركيزٍ وإتقان…', 11.92, 14.40), (2, 'أليس كذلك؟', 14.62, 15.32),
 (3, 'طيِّب، وعندما لا ينظرُ إلينا أحد؟', 15.74, 18.49), (3, 'نتذكَّرُ أنَّ اللهَ يرانا ويعلمُ ما نعمل', 19.07, 22.47), (3, 'فنحرصُ على الخيرِ في كلِّ وقت!', 22.79, 25.12),
 (4, 'والإحسانُ هو:', 25.84, 26.67), (4, '«أن تعبدَ اللهَ كأنَّكَ تراه»', 27.27, 29.48), (4, '«فإن لم تكن تراهُ فإنَّه يراك»', 29.85, 31.99),
 (5, 'يعني أن نعبدَ اللهَ بإخلاصٍ وخشوع', 32.90, 35.60), (5, 'ونتذكَّرُ دائمًا أنَّه يرانا ويسمعُنا', 35.70, 39.33), (5, 'والإحسانُ هو أعلى مراتبِ الدِّين!', 39.76, 42.46),
 (6, 'مثلًا… عندما نصلِّي', 42.92, 44.76), (6, 'نصلِّي بهدوءٍ وننتبهُ لما نقول', 45.14, 47.87), (6, 'لأنَّنا نقفُ بين يدَيِ الله', 48.19, 50.20),
 (7, 'وحتى عندما نكونُ وحدَنا', 50.83, 52.45), (7, 'نختارُ الصِّدقَ ونبتعدُ عن الخطأ', 52.59, 55.02), (7, 'لأنَّ اللهَ يرانا أينما كنَّا', 55.41, 57.08),
 (8, 'هيّا نتذكَّرُ معًا:', 57.52, 58.82), (8, 'ما الإحسان؟', 59.30, 60.05), (8, 'أن نعبدَ اللهَ كأنَّنا نراه', 60.90, 63.17), (8, 'فإن كنَّا لا نراهُ فإنَّه يرانا!', 63.36, 65.94),
 (9, 'أحسنتم يا أبطال!', 66.68, 68.00), (9, 'فلنكن محسنينَ في عبادتِنا وكلامِنا وأعمالِنا', 68.36, 72.15), (9, 'إلى اللقاءِ في درسٍ جديد!', 72.64, 74.40),
]
r = subprocess.run(['ffmpeg', '-v', 'error', '-i', VO, '-ac', '1', '-ar', '24000', '-f', 'f32le', '-'], capture_output=True)
x = np.frombuffer(r.stdout, np.float32).astype(float); SR = 24000; dur = len(x) / SR
ph = [{'p': p, 'text': t, 'a': round(a + OFF, 3), 'b': round(b + OFF, 3)} for p, t, a, b in PHRASES]
hop = SR // FPS; n = int((dur + OFF + TAIL) * FPS); env = np.zeros(n)
for i in range(n):
    j = int((i / FPS - OFF) * SR)
    if 0 <= j < len(x) - hop: env[i] = np.sqrt(np.mean(x[j:j + hop] ** 2))
env = env / (np.percentile(env[env > 0], 95) + 1e-9); env = np.clip(env, 0, 1.2)
env = np.convolve(env, [.25, .5, .25], 'same')
data = {'off': OFF, 'duration': round(dur + OFF + TAIL, 2), 'phrases': ph, 'env': [round(v, 3) for v in env], 'fps': FPS}
json.dump(data, open(os.path.join(HERE, 'timing.json'), 'w'), ensure_ascii=False)
open(os.path.join(HERE, 'timing.js'), 'w').write('window.TIMING = ' + json.dumps(data, ensure_ascii=False) + ';\n')
print(f'✓ {len(ph)} عبارة — المدة {data["duration"]}s')
